// @ts-expect-error Bun's test module is provided by the test runtime, not the Next.js app types.
import { beforeEach, describe, expect, mock, test } from "bun:test";

/**
 * The wrapped-ClientKey restore tiers.
 *
 * These import the REAL src/lib/fhe.ts. An earlier attempt at this area used hand-written
 * "mirrors" of the logic; deleting the fingerprint gate from the shipped file left every
 * assertion green. Each test below is paired with a mutation that must turn it red — see
 * fheKeyRestore.mutations.md next to this file.
 *
 * Nothing here touches wasm. loadFhe() throws outside a browser and shimming `window` only gets
 * far enough to die inside wasm-bindgen, poisoning the module's promise for every later test. So
 * the fixture is a fixed client key and only the storage/restore paths are exercised; the derive
 * path (generateKeysFromSeed) is deliberately out of scope.
 */

const WALLET = "0x1111111111111111111111111111111111111111";
const OTHER = "0x2222222222222222222222222222222222222222";

/**
 * A fixed 44,952-hex-char client key — the exact length the wasm returns, so the base64/hex
 * round trip is exercised at real size. Generated by a deterministic LCG rather than pasted, so
 * it is byte-identical on every run without a 44 KB literal in the file.
 */
function fixtureClientKey(): string {
  let x = 0x12345678;
  let out = "";
  while (out.length < 44952) {
    x = (x * 1103515245 + 12345) & 0x7fffffff;
    out += (x & 0xff).toString(16).padStart(2, "0");
  }
  return out.slice(0, 44952);
}
const CLIENT_KEY = fixtureClientKey();

// ── browser shims ────────────────────────────────────────────────────────────
function memStorage() {
  const m = new Map<string, string>();
  return {
    getItem: (k: string) => (m.has(k) ? m.get(k)! : null),
    setItem: (k: string, v: string) => void m.set(k, v),
    removeItem: (k: string) => void m.delete(k),
    clear: () => m.clear(),
    get size() { return m.size; },
    _dump: () => Object.fromEntries(m),
  };
}

let sessionStore: ReturnType<typeof memStorage>;
let localStore: ReturnType<typeof memStorage>;
let serverRow: Record<string, unknown> | null;
let putBodies: Array<Record<string, unknown>>;
let dispatched: string[];

// One AES key for the whole suite, standing in for the note enc-key.
const AES_KEY = await crypto.subtle.importKey(
  "raw",
  new Uint8Array(32).fill(7),
  { name: "AES-GCM" },
  false,
  ["encrypt", "decrypt"],
);

const signer = {
  getAddress: async () => WALLET,
  signMessage: async () => "0x" + "ab".repeat(65),
};
let currentSigner: unknown = signer;

const realNexus = await import("../nexus").catch(() => ({}));
mock.module("../nexus", () => ({ ...realNexus, getSigner: () => currentSigner }));
const realExec = await import("../tradeExecutorClient").catch(() => ({}));
mock.module("../tradeExecutorClient", () => ({
  ...realExec,
  getTradeExecutorBaseUrl: () => "https://executor.test",
}));
// Spread the real module: other files (decryptorClient, …) import names from it, and replacing
// it wholesale breaks their imports. Only the two signing helpers are stubbed.
const realAuthHeaders = await import("../walletAuthHeaders");
mock.module("../walletAuthHeaders", () => ({
  ...realAuthHeaders,
  getWalletAuthHeaders: async () => ({ "X-Wallet-Address": WALLET }),
  getWalletWriteAuthHeaders: async () => ({ "X-Wallet-Address": WALLET }),
}));

// Real AES-GCM (crypto.subtle is a genuine global under bun) with only the KEY DERIVATION
// stubbed — so the actual wrap/unwrap format is exercised, not a stand-in for it.
const realNoteAuth = await import("../noteAuth");
mock.module("../noteAuth", () => ({
  ...realNoteAuth,
  deriveEncKey: async () => AES_KEY,
}));

const fhe = await import("../fhe");
const { fingerprintClientKey } = await import("../fheKeyWarmup");

const SESSION_KEY = (w: string) => `siphon.fhe.clientKey.v3.${w.toLowerCase()}`;
const LEGACY_KEY = (w: string) => `siphon.fhe.clientKey.v2.${w.toLowerCase()}`;

function bytesToBase64(bytes: Uint8Array): string {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) {
    s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return btoa(s);
}
function hexToBytes(hex: string): Uint8Array {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.substr(i * 2, 2), 16);
  return out;
}

async function payload(over: Record<string, unknown> = {}) {
  return {
    v: 2,
    k: bytesToBase64(hexToBytes(CLIENT_KEY)),
    signerAddress: WALLET.toLowerCase(),
    derived: true,
    fp: await fingerprintClientKey(CLIENT_KEY),
    ...over,
  };
}

async function wrap(p: Record<string, unknown>) {
  return realNoteAuth.encryptBlob(AES_KEY, p);
}

beforeEach(() => {
  sessionStore = memStorage();
  localStore = memStorage();
  serverRow = null;
  putBodies = [];
  dispatched = [];
  currentSigner = signer;

  (globalThis as Record<string, unknown>).window = {
    sessionStorage: sessionStore,
    localStorage: localStore,
    dispatchEvent: (e: { type: string }) => { dispatched.push(e.type); return true; },
    CustomEvent: class { type: string; constructor(t: string) { this.type = t; } },
  };
  (globalThis as Record<string, unknown>).localStorage = localStore;
  (globalThis as Record<string, unknown>).sessionStorage = sessionStore;
  if (!(globalThis as Record<string, unknown>).CustomEvent) {
    (globalThis as Record<string, unknown>).CustomEvent =
      class { type: string; constructor(t: string) { this.type = t; } };
  }

  (globalThis as Record<string, unknown>).fetch = async (url: string, init?: RequestInit) => {
    if (String(url).includes("/fheKeyBlob") && init?.method === "PUT") {
      putBodies.push(JSON.parse(String(init.body)));
      return { ok: true, json: async () => ({ status: "success" }) };
    }
    if (String(url).includes("/fheKeyBlob")) {
      if (!serverRow) return { ok: false, status: 404, json: async () => ({}) };
      return { ok: true, json: async () => serverRow };
    }
    throw new Error(`unexpected fetch ${url}`);
  };
});

// ── getStoredClientKey: the synchronous tier ─────────────────────────────────

describe("getStoredClientKey", () => {
  test("returns the key from a well-formed session payload", async () => {
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await payload()));
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("MUTATION signerAddress check skipped on the sessionStorage tier — rejects a foreign blob", async () => {
    // Wallet A's key sitting under wallet B's id. Well-formed, correct fingerprint, wrong owner.
    // Restore writes through to sessionStorage, so trusting this once trusts it all tab long.
    sessionStore.setItem(
      SESSION_KEY(WALLET),
      JSON.stringify(await payload({ signerAddress: OTHER.toLowerCase() })),
    );
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
  });

  test("rejects a payload with no signerAddress at all", async () => {
    const p = await payload();
    delete (p as Record<string, unknown>).signerAddress;
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(p));
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
  });

  test("MUTATION v1/v2 dispatch swapped — v1 payloads still decode as raw hex", async () => {
    sessionStore.setItem(
      SESSION_KEY(WALLET),
      JSON.stringify(await payload({ v: 1, k: CLIENT_KEY })),
    );
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("MUTATION legacy plaintext migrated instead of purged — v2 entries are deleted, never read", async () => {
    localStore.setItem(LEGACY_KEY(WALLET), CLIENT_KEY);
    sessionStore.setItem(LEGACY_KEY(WALLET), CLIENT_KEY);
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
    expect(localStore.getItem(LEGACY_KEY(WALLET))).toBeNull();
    expect(sessionStore.getItem(LEGACY_KEY(WALLET))).toBeNull();
  });

  test("a random (non-derived) key still serves the tab, as before", async () => {
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await payload({ derived: false })));
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });
});

// ── restore tiers ────────────────────────────────────────────────────────────

describe("getOrCreateClientKey restore", () => {
  test("restores from the wrapped localStorage tier and writes through to sessionStorage", async () => {
    localStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await wrap(await payload())));
    expect(await fhe.getOrCreateClientKey(WALLET)).toBe(CLIENT_KEY);
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("restores from the server tier when localStorage is empty", async () => {
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    expect(await fhe.getOrCreateClientKey(WALLET)).toBe(CLIENT_KEY);
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("MUTATION fingerprint check removed — a tampered key is rejected, not returned", async () => {
    const bad = await payload({ fp: "0".repeat(16) });
    localStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await wrap(bad)));
    // No other tier and no signer-driven derive can run here without wasm, so a rejected blob
    // must surface as a throw rather than as the wrong key.
    await expect(fhe.getOrCreateClientKey(WALLET)).rejects.toThrow();
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
  });

  test("MUTATION fingerprint-absent blob accepted — a blob with no fp is rejected", async () => {
    const p = await payload();
    delete (p as Record<string, unknown>).fp;
    localStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await wrap(p)));
    await expect(fhe.getOrCreateClientKey(WALLET)).rejects.toThrow();
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
  });

  test("MUTATION derived gate removed — a non-derived blob is never restored from disk", async () => {
    localStore.setItem(
      SESSION_KEY(WALLET),
      JSON.stringify(await wrap(await payload({ derived: false }))),
    );
    await expect(fhe.getOrCreateClientKey(WALLET)).rejects.toThrow();
    expect(fhe.getStoredClientKey(WALLET)).toBeNull();
  });

  test("MUTATION signerAddress check removed — a foreign wrapped blob is rejected", async () => {
    localStore.setItem(
      SESSION_KEY(WALLET),
      JSON.stringify(await wrap(await payload({ signerAddress: OTHER.toLowerCase() }))),
    );
    await expect(fhe.getOrCreateClientKey(WALLET)).rejects.toThrow();
  });

  test("MUTATION owner binding removed — refuses to store one wallet's key under another's id", async () => {
    // Build.tsx used to pass a user-TYPED withdraw address here.
    await expect(fhe.getOrCreateClientKey(OTHER)).rejects.toThrow(/refusing to store/i);
  });

  test("concurrent callers share one restore (no duplicate round trips)", async () => {
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    let gets = 0;
    const prev = (globalThis as Record<string, unknown>).fetch as typeof fetch;
    (globalThis as Record<string, unknown>).fetch = async (u: string, i?: RequestInit) => {
      if (String(u).includes("/fheKeyBlob") && i?.method !== "PUT") gets++;
      return prev(u as string, i);
    };
    const [a, c] = await Promise.all([
      fhe.getOrCreateClientKey(WALLET),
      fhe.getOrCreateClientKey(WALLET),
    ]);
    expect(a).toBe(CLIENT_KEY);
    expect(c).toBe(CLIENT_KEY);
    expect(gets).toBe(1);
  });

  test("no restore path ever issues a write", async () => {
    // getWalletWriteAuthHeaders always signs a fresh nonce, so ANY write here would put a wallet
    // popup on the most common path — the exact thing this change removes. The blob is published
    // by /uploadServerKey instead, which already holds a challenge.
    localStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await wrap(await payload())));
    await fhe.getOrCreateClientKey(WALLET);
    expect(putBodies.length).toBe(0);

    sessionStore.clear();
    localStore.clear();
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    await fhe.getOrCreateClientKey(WALLET);
    expect(putBodies.length).toBe(0);
  });

  test("MUTATION plaintext written to localStorage — disk only ever holds ciphertext", async () => {
    // Exercises the WRITE path: a server restore is cached to disk, so this asserts what that
    // cache actually contains. Checking for the hex alone would miss it — the payload stores the
    // key base64-encoded, so a plaintext leak would not contain the hex string at all.
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    await fhe.getOrCreateClientKey(WALLET);

    const stored = localStore.getItem(SESSION_KEY(WALLET));
    expect(stored).not.toBeNull(); // the write path must have run, or this proves nothing
    const parsed = JSON.parse(String(stored)) as Record<string, unknown>;
    expect(Object.keys(parsed).sort()).toEqual(["enc_blob", "iv"]);
    expect(parsed.k).toBeUndefined();
    expect(parsed.signerAddress).toBeUndefined();

    const b64 = bytesToBase64(hexToBytes(CLIENT_KEY));
    for (const [, v] of Object.entries(localStore._dump())) {
      expect(String(v)).not.toContain(CLIENT_KEY.slice(0, 64));
      expect(String(v)).not.toContain(b64.slice(0, 64));
    }
  });

  test("a corrupt localStorage blob falls through to the server tier", async () => {
    localStore.setItem(SESSION_KEY(WALLET), JSON.stringify({ enc_blob: "!!", iv: "!!" }));
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    expect(await fhe.getOrCreateClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("a server 500 does not propagate", async () => {
    (globalThis as Record<string, unknown>).fetch = async () => ({
      ok: false, status: 500, json: async () => ({}),
    });
    // Nothing to restore and no wasm to derive with — a throw is fine, a HANG or a 500 leaking
    // out as an unhandled rejection is not.
    await expect(fhe.getOrCreateClientKey(WALLET)).rejects.toThrow();
  });
});

describe("restoreInFlight", () => {
  test("is null when nothing is running and resolves while a restore is", async () => {
    expect(fhe.restoreInFlight(WALLET)).toBeNull();
    const b = await wrap(await payload());
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    const p = fhe.getOrCreateClientKey(WALLET);
    const waiter = fhe.restoreInFlight(WALLET);
    expect(waiter).not.toBeNull();
    await waiter;
    await p;
    expect(fhe.getStoredClientKey(WALLET)).toBe(CLIENT_KEY);
  });

  test("resolves rather than rejecting when the restore fails", async () => {
    const p = fhe.getOrCreateClientKey(OTHER).catch(() => {});
    const waiter = fhe.restoreInFlight(OTHER);
    if (waiter) await waiter; // must not throw
    await p;
  });
});

// ── the wrapped blob handed to /uploadServerKey ──────────────────────────────

describe("wrappedClientKeyForUpload", () => {
  test("returns ciphertext the server cannot read, and that unwraps back to the key", async () => {
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await payload()));
    const out = await fhe.wrappedClientKeyForUpload(WALLET);
    expect(out).not.toBeNull();
    expect(out!.client_key_v).toBe(2);
    expect(out!.client_key_fp).toBe(await fingerprintClientKey(CLIENT_KEY));
    // No plaintext, in either encoding.
    const b64 = bytesToBase64(hexToBytes(CLIENT_KEY));
    expect(out!.enc_client_key).not.toContain(CLIENT_KEY.slice(0, 64));
    expect(out!.enc_client_key).not.toContain(b64.slice(0, 64));
    // …and it really is the key, not just opaque bytes.
    const back = await realNoteAuth.decryptBlob<Record<string, unknown>>(
      AES_KEY, out!.enc_client_key, out!.client_key_iv,
    );
    expect(back.signerAddress).toBe(WALLET.toLowerCase());
    expect(back.derived).toBe(true);
  });

  test("refuses to publish a random (non-derived) key", async () => {
    // A random key cannot be re-derived on another device, so publishing it hands device two a
    // key it can never reproduce.
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await payload({ derived: false })));
    expect(await fhe.wrappedClientKeyForUpload(WALLET)).toBeNull();
  });

  test("refuses when the session payload belongs to another wallet", async () => {
    sessionStore.setItem(
      SESSION_KEY(WALLET),
      JSON.stringify(await payload({ signerAddress: OTHER.toLowerCase() })),
    );
    expect(await fhe.wrappedClientKeyForUpload(WALLET)).toBeNull();
  });

  test("returns null rather than throwing when there is no signer", async () => {
    sessionStore.setItem(SESSION_KEY(WALLET), JSON.stringify(await payload()));
    currentSigner = null;
    expect(await fhe.wrappedClientKeyForUpload(WALLET)).toBeNull();
  });

  test("returns null when nothing is stored", async () => {
    expect(await fhe.wrappedClientKeyForUpload(WALLET)).toBeNull();
  });
});

// ── Solana key owners (Phantom) ──────────────────────────────────────────────

describe("getOrCreateClientKey for a Solana address", () => {
  const SOL = "8xueCcQRMhKo5CtppfmxXar2LuVaHfiiN3VzhxepqNEg";
  const SOL_OTHER = "5RovhnQbzGyEBofjQpBa1qi6Wh7SsZztTZMWAE24poGq";

  function connectPhantom(pubkey: string) {
    (globalThis as Record<string, unknown> & { window: Record<string, unknown> }).window.solana = {
      isPhantom: true,
      publicKey: { toString: () => pubkey },
      signMessage: async () => ({ signature: new Uint8Array(64).fill(9) }),
    };
  }

  function countKeyBlobGets(): () => number {
    let gets = 0;
    const prev = (globalThis as Record<string, unknown>).fetch as typeof fetch;
    (globalThis as Record<string, unknown>).fetch = async (u: string, i?: RequestInit) => {
      if (String(u).includes("/fheKeyBlob")) gets++;
      return prev(u as string, i);
    };
    return () => gets;
  }

  test("restores the Phantom-owned key from the wrapped local tier, ignoring the EVM signer", async () => {
    // The EVM signer is a DIFFERENT account; using it would throw "refusing to store".
    connectPhantom(SOL);
    localStore.setItem(
      SESSION_KEY(SOL),
      JSON.stringify(await wrap(await payload({ signerAddress: SOL.toLowerCase() }))),
    );
    expect(await fhe.getOrCreateClientKey(SOL)).toBe(CLIENT_KEY);
    expect(fhe.getStoredClientKey(SOL)).toBe(CLIENT_KEY);
  });

  test("MUTATION Solana ownership check removed — Phantom on another account is refused", async () => {
    connectPhantom(SOL_OTHER);
    await expect(fhe.getOrCreateClientKey(SOL)).rejects.toThrow(/refusing to store/i);
  });

  test("MUTATION server tier kept for Solana — it is never queried (its auth is EVM-only)", async () => {
    connectPhantom(SOL);
    const b = await wrap(await payload({ signerAddress: SOL.toLowerCase() }));
    serverRow = { enc_client_key: b.enc_blob, client_key_iv: b.iv, client_key_v: 2 };
    const gets = countKeyBlobGets();
    // Local is empty, so this falls through to derive, which needs wasm and throws here.
    await expect(fhe.getOrCreateClientKey(SOL)).rejects.toThrow();
    expect(gets()).toBe(0);
  });
});

describe("seedFromSignature", () => {
  test("bare ed25519 hex and 0x-prefixed hex give the same 32-byte seed", () => {
    const hex = "09".repeat(64);
    expect(fhe.seedFromSignature(hex)).toBe(fhe.seedFromSignature(`0x${hex}`));
    expect(fhe.seedFromSignature(hex)).toMatch(/^0x[0-9a-f]{64}$/);
  });

  test("different signatures give different seeds", () => {
    expect(fhe.seedFromSignature("09".repeat(64))).not.toBe(fhe.seedFromSignature("0a".repeat(64)));
  });
});
