import { defaultChainLabel, defaultDexForChain, type BuilderChainOpts } from "./blocks";
import type { ParsedPrompt } from "./types";

/** Structural defaults for LLM-parsed strategies (no regex inference). */
export function createDefaultParsed(
  raw: string,
  patch?: Partial<ParsedPrompt>,
  chainOpts?: BuilderChainOpts,
): ParsedPrompt {
  return {
    raw,
    strategy: "Limit Order",
    side: null,
    depositChain: defaultChainLabel(),
    withdrawChain: defaultChainLabel(),
    bridgeToChain: null,
    dex: defaultDexForChain(chainOpts),
    coin: null,
    toCoin: null,
    amount: null,
    swapAmount: null,
    priceGoal: null,
    rangeLow: null,
    rangeHigh: null,
    gridLevels: null,
    sliceCount: null,
    intervalSeconds: null,
    maxSlippageBps: null,
    intervals: null,
    wallet: null,
    includeSwap: false,
    includeWithdraw: false,
    includeLend: false,
    lendAction: null,
    pipelineHops: null,
    includeBridge: false,
    useLoop: false,
    loopIntervalValue: null,
    loopIntervalUnit: null,
    includeSchedule: false,
    scheduleValue: null,
    scheduleUnit: null,
    polyMarketQuery: null,
    polyOutcome: null,
    polyTokenId: null,
    polyMarketId: null,
    polyMarketQuestion: null,
    polyOdds: null,
    polyOutcomes: null,
    hlCoin: null,
    hlLeverage: null,
    hlTakeProfit: null,
    hlStopLoss: null,
    ...patch,
  };
}
