# Deploy Siphon Devnet stack on Ethereum Sepolia (tSOL + VaultKernel).
# Requires siphon-contracts-v2/evm/.env with PRIVATE_KEY (Sepolia-funded).
#
#   powershell -File script/deploy-sepolia-devnet.ps1

$ErrorActionPreference = "Stop"
$Evm = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path (Join-Path $Evm "foundry.toml"))) {
  throw "Could not locate evm/ next to script/"
}
Set-Location $Evm

$envFile = Join-Path $Evm ".env"
if (-not (Test-Path $envFile)) {
  throw "Missing .env - set PRIVATE_KEY and ETH_SEPOLIA_RPC_URL first"
}

Get-Content $envFile | ForEach-Object {
  if ($_ -match '^\s*([^#=]+)=(.*)$') {
    $k = $matches[1].Trim()
    $v = $matches[2].Trim().Trim('"').Trim("'")
    if ($k) { Set-Item -Path ("Env:" + $k) -Value $v }
  }
}

$pk = ""
if ($env:PRIVATE_KEY) { $pk = $env:PRIVATE_KEY.Trim() }
if (-not $pk -or $pk.Length -lt 60) {
  throw "PRIVATE_KEY missing/invalid in .env"
}

# Prefer a reliable public Sepolia RPC (publicnode often 403s from this host).
$rpc = "https://sepolia.gateway.tenderly.co"
$env:ETH_SEPOLIA_RPC_URL = $rpc
$env:ETH_RPC_TIMEOUT = "120"

Write-Host "==> deriving deployer"
$addr = (cast wallet address --private-key $pk).Trim()
Write-Host "Deployer: $addr"
if (-not $env:GOVERNANCE_ADDRESS -or -not $env:GOVERNANCE_ADDRESS.Trim()) {
  $env:GOVERNANCE_ADDRESS = $addr
}
if (-not $env:POSTMAN_ADDRESS -or -not $env:POSTMAN_ADDRESS.Trim()) {
  $env:POSTMAN_ADDRESS = $addr
}

$balEther = cast balance $addr --rpc-url $rpc --ether
Write-Host "Balance (ETH): $balEther"
$balWei = [decimal](cast balance $addr --rpc-url $rpc)
if ($balWei -lt 50000000000000000) {
  throw "Deployer needs >= 0.05 Sepolia ETH. Balance wei=$balWei"
}

$depDir = Join-Path $Evm "deployments"
New-Item -ItemType Directory -Force -Path $depDir | Out-Null
$logPath = Join-Path $depDir "sepolia-deploy.log"

Write-Host "==> DeployDevnetSolPool (tSOL + Uniswap V3 pool vs WETH)"
$solOut = forge script script/DeployDevnetSolPool.s.sol:DeployDevnetSolPool `
  --rpc-url $rpc --private-key $pk --broadcast -vv 2>&1 | Out-String
Add-Content -Path $logPath -Value $solOut
Write-Host $solOut

$sol = ([regex]::Match($solOut, 'NEXT_PUBLIC_SEPOLIA_SOL_TOKEN=\s*(0x[0-9a-fA-F]{40})')).Groups[1].Value
if (-not $sol) {
  $sol = ([regex]::Match($solOut, 'Deployed tSOL\s+(0x[0-9a-fA-F]{40})')).Groups[1].Value
}
if (-not $sol) {
  $sol = ([regex]::Match($solOut, 'Using existing tSOL\s+(0x[0-9a-fA-F]{40})')).Groups[1].Value
}
if (-not $sol) { throw "Could not parse tSOL address from DeployDevnetSolPool output" }
Write-Host "tSOL=$sol"
$env:ASSET_TOKEN = $sol
if (-not $env:SETTLEMENT_DST_TOKEN -or -not $env:SETTLEMENT_DST_TOKEN.Trim()) {
  $env:SETTLEMENT_DST_TOKEN = "0xfFf9976782d46CC05630D1f6eBAb18b2324d6B14"
}
if (-not $env:SWAP_ROUTER -or -not $env:SWAP_ROUTER.Trim()) {
  $env:SWAP_ROUTER = "0x3bFA4769FB09eefC5a80d6E87c3B9C650f7Ae48E"
}

Write-Host "==> DeployVaultStack (ASSET_TOKEN=tSOL)"
$vaultOut = forge script script/DeployVaultStack.s.sol:DeployVaultStack `
  --rpc-url $rpc --private-key $pk --broadcast -vv 2>&1 | Out-String
Add-Content -Path $logPath -Value $vaultOut
Write-Host $vaultOut

$addrJson = Join-Path $Evm "deployments\chain-11155111\deployed_addresses.json"
if (-not (Test-Path $addrJson)) { throw "Missing $addrJson after deploy" }
$d = Get-Content $addrJson -Raw | ConvertFrom-Json

$appEnv = @"
# Sepolia Devnet custody (generated by deploy-sepolia-devnet.ps1)
NEXT_PUBLIC_TRADE_EXECUTOR_URL=http://127.0.0.1:5010
NEXT_PUBLIC_CLUSTER=devnet
NEXT_PUBLIC_SKIP_TRUST=1
NEXT_PUBLIC_ASP_SCREEN=0
NEXT_PUBLIC_ASP_FAIL_CLOSED=0
NEXT_PUBLIC_SOLANA_USDC_MINT=4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU

NEXT_PUBLIC_DEVNET_VAULT_CHAIN_ID=11155111
NEXT_PUBLIC_SEPOLIA_SOL_TOKEN=$sol

NEXT_PUBLIC_V3_SEPOLIA_VAULT_KERNEL=$($d.VaultKernel)
NEXT_PUBLIC_V3_SEPOLIA_COMPLIANCE_HUB=$($d.ComplianceHub)
NEXT_PUBLIC_V3_SEPOLIA_SETTLEMENT_ADAPTER=$($d.SettlementAdapter)
NEXT_PUBLIC_V3_SEPOLIA_DEPLOY_BLOCK=$($d.DeployBlock)
NEXT_PUBLIC_V3_SEPOLIA_EXECUTOR_URL=http://127.0.0.1:5010
"@

$outPath = Join-Path $Evm "deployments\chain-11155111\app.env.local.snippet"
Set-Content -Path $outPath -Value $appEnv -Encoding utf8
Write-Host ""
Write-Host "======== SEPOLIA DEPLOY OK ========"
Write-Host "tSOL:            $sol"
Write-Host "VaultKernel:     $($d.VaultKernel)"
Write-Host "ComplianceHub:   $($d.ComplianceHub)"
Write-Host "Settlement:      $($d.SettlementAdapter)"
Write-Host "DeployBlock:     $($d.DeployBlock)"
Write-Host "Wrote $outPath"
